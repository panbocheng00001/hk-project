"""ext_server.py —— Chrome 扩展的本地数据服务（无 CDP 方案的 Python 侧）
=====================================================================
为什么需要它：
    扩展跑在浏览器里，不能直接读本地文件；所有「配置、图片字节、OTP、状态回传」
    都通过这个 127.0.0.1 上的小 HTTP 服务完成。

接口：
    GET  /ping                 健康检查
    GET  /config               申请人资料 + 办事处优先序 + 图片路径
    GET  /file?name=<相对路径>  返回图片原始字节（扩展用 DataTransfer 塞进 input[type=file]）
    GET  /otp                  读 otp.txt（没读到返回 {"code": null}）
    GET  /commands             返回给扩展的指令（如 {"stop": false}）
    POST /status               扩展上报进度（写 runs/ext_status.jsonl）
    POST /result               扩展上报最终结果
    GET  /test                 一个本地测试页（验证扩展是否注入成功）

用法：
    python ext_server.py            # 前台跑，Ctrl+C 停
    python ext_server.py --port 8765
"""
