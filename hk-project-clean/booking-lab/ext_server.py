def _applicant(cfg: dict, who: str) -> dict:
    """按窗口代号取申请人资料。

    支持两种配置形态：
      · 新版：cfg["applicants"] = [{ "id": "w1", ... }, ...]   ← 多人（同事一起办）
      · 旧版：cfg["applicant"] = {...}                        ← 单人，视为 w1
    """
    people = cfg.get("applicants")
    if isinstance(people, list) and people:
        who = (who or "").strip()
        if who:
            for p in people:
                if str(p.get("id", "")).strip() == who:
                    return p
        return people[0]           # 没指定就用第一个
    return cfg.get("applicant") or {}


def _config(who: str = "") -> dict:
    try:
        cfg = json.loads(CONFIG.read_text(encoding="utf-8-sig"))
    except Exception:
        cfg = {}
    ap = _applicant(cfg, who)
    people = cfg.get("applicants")
    total = len(people) if isinstance(people, list) and people else 1
    return {
        "who": (ap.get("id") or who or "w1"),
        "total": total,
        "applicant": {
            "id": ap.get("id", who or "w1"),
            "title": ap.get("title", ""),
            "name_cn": ap.get("name_cn", ""),
            "doc_no": ap.get("doc_no", ""),
            "doc_type": ap.get("doc_type", ""),
            "dl_no": ap.get("dl_no", ""),
            "email": ap.get("email", ""),
            "phone": ap.get("phone", ""),
            "doc_file": ap.get("doc_file", ""),
            "dl_file": ap.get("dl_file", ""),
        },
        "bureau_preference": ap.get("bureau_preference") or cfg.get("bureau_preference") or [],
        "country": cfg.get("country", "mainland"),
        "files_dir": cfg.get("files_dir", "files/"),
    }


