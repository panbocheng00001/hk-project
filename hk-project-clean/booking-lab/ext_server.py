def export_cookies(snap: dict, tag: str = "") -> int:
    """把快照里的 cookie 导出成三种格式，直接能喂给接口脚本：

        runs\\cookies.txt        Netscape 格式（curl -b cookies.txt / requests cookiejar 都能吃）
        runs\\cookies.json       结构化，保留 httpOnly / secure / sameSite 等信息
        runs\\cookie_header.txt  一行 Cookie: ... 头，最省事，粘进任何请求都行
    """
    ck = snap.get("cookies") or []
    if not ck:
        return 0
    RUNS.mkdir(exist_ok=True)

    lines = ["# Netscape HTTP Cookie File",
             "# generated by ext_server.py", ""]
    for c in ck:
        dom = str(c.get("domain") or "")
        if not dom:
            continue
        flag = "TRUE" if dom.startswith(".") else "FALSE"
        path = str(c.get("path") or "/")
        secure = "TRUE" if c.get("secure") else "FALSE"
        try:
            exp = int(c.get("expirationDate") or 0)
        except Exception:
            exp = 0
        lines.append("\t".join([dom, flag, path, secure, str(exp),
                                str(c.get("name") or ""), str(c.get("value") or "")]))
    (RUNS / "cookies.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")

    (RUNS / "cookies.json").write_text(
        json.dumps({"tag": tag, "savedAt": datetime.now().isoformat(timespec="seconds"),
                    "cookies": ck}, ensure_ascii=False, indent=1), encoding="utf-8")

    hdr = "; ".join(f"{c.get('name')}={c.get('value')}" for c in ck if c.get("name"))
    (RUNS / "cookie_header.txt").write_text(hdr, encoding="utf-8")
    return len(ck)


